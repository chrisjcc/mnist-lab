"""Minimum Viable Experiment (MVE) acceptance criteria gate verifier.

Supports two execution modes:
1. Default mode (`python scripts/run_mve_evaluation.py`):
   Verifies the full MVE baseline artifacts generated by `dvc repro` / `make train`
   against strict MVE acceptance gates (`test_acc >= 0.9900`, `macro_f1 >= 0.9890`,
   per-class F1 `>= 0.9800`, single-sample latency `p95_ms < 25.0`, etc.).
2. Smoke mode (`python scripts/run_mve_evaluation.py --smoke`):
   Executes a fast, self-contained 2-epoch synthetic pipeline in a temporary
   directory and verifies all 5 MVE structural and convergence gates for CI.
"""

from __future__ import annotations

import argparse
import csv
import logging
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

from mnist_pipeline.config import load_hydra_config
from mnist_pipeline.data import preprocess_mnist_data
from mnist_pipeline.evaluate import benchmark_checkpoint, evaluate_checkpoint
from mnist_pipeline.reporting import generate_all_reports
from mnist_pipeline.train import train_model
from mnist_pipeline.utils import load_json

LOGGER = logging.getLogger(__name__)


@dataclass(frozen=True)
class GateResult:
    """Verification result for a single MVE acceptance gate.

    Attributes:
        gate_id: Gate identifier string (e.g., `"Gate 1"`).
        name: Short gate title.
        passed: True if the acceptance criterion passed.
        details: Human-readable metric summary compared against threshold.
    """

    gate_id: str
    name: str
    passed: bool
    details: str


def verify_mve_gates(
    root_dir: Path,
    smoke: bool = False,
) -> list[GateResult]:
    """Evaluate all 5 MVE acceptance gates against generated pipeline artifacts.

    Args:
        root_dir: Directory containing `data/`, `artifacts/`, and `docs/`.
        smoke: If True, apply smoke-test sample count and accuracy thresholds.

    Returns:
        List of 5 `GateResult` objects.
    """
    repo_root = Path(__file__).resolve().parent.parent
    cfg = load_hydra_config(config_dir=repo_root / "configs")
    results: list[GateResult] = []

    # Gate 1: Data Integrity & Split Balance
    split_meta_path = root_dir / "data/processed/split_metadata.json"
    if not split_meta_path.exists():
        results.append(GateResult("Gate 1", "Data Integrity", False, f"Missing {split_meta_path}"))
    else:
        meta = load_json(split_meta_path)
        splits = meta.get("splits", {})
        train_n = int(splits.get("train", {}).get("num_examples", 0))
        val_n = int(splits.get("val", {}).get("num_examples", 0))
        test_n = int(splits.get("test", {}).get("num_examples", 0))

        expected_train = 180 if smoke else 54000
        expected_val = 20 if smoke else 6000
        expected_test = 60 if smoke else 10000
        counts_ok = train_n == expected_train and val_n == expected_val and test_n == expected_test
        train_dist = splits.get("train", {}).get("class_distribution", {})
        all_classes_present = all(int(train_dist.get(str(c), 0)) > 0 for c in range(10))
        passed_g1 = bool(counts_ok and all_classes_present)
        results.append(
            GateResult(
                "Gate 1",
                "Data Integrity",
                passed_g1,
                f"train={train_n} (exp {expected_train}), "
                f"val={val_n} (exp {expected_val}), "
                f"test={test_n} (exp {expected_test}), "
                f"all_10_classes={all_classes_present}",
            )
        )

    # Gate 2: Training Convergence
    history_path = root_dir / "artifacts/reports/train_history.csv"
    if not history_path.exists():
        results.append(
            GateResult("Gate 2", "Training Convergence", False, f"Missing {history_path}")
        )
    else:
        with history_path.open("r", encoding="utf-8") as handle:
            rows = list(csv.DictReader(handle))
        first_loss = float(rows[0]["train_loss"])
        last_loss = float(rows[-1]["train_loss"])
        best_val_acc = max(float(r.get("val_accuracy", r.get("val_acc", 0.0))) for r in rows)
        best_val_loss = min(float(r["val_loss"]) for r in rows)
        min_val_acc_thresh = 0.70 if smoke else cfg.evaluate.mve_min_val_accuracy
        max_val_loss_thresh = 1.50 if smoke else 0.0500
        passed_g2 = (
            last_loss < first_loss
            and best_val_acc >= min_val_acc_thresh
            and best_val_loss <= max_val_loss_thresh
        )
        results.append(
            GateResult(
                "Gate 2",
                "Training Convergence",
                passed_g2,
                f"train_loss {first_loss:.4f} -> {last_loss:.4f}, "
                f"best_val_acc={best_val_acc:.4f} (>={min_val_acc_thresh:.4f}), "
                f"best_val_loss={best_val_loss:.4f} (<={max_val_loss_thresh:.4f})",
            )
        )

    # Gate 3: Held-Out Test Generalization
    test_metrics_path = root_dir / "artifacts/evaluation/test_metrics.json"
    if not test_metrics_path.exists():
        results.append(
            GateResult(
                "Gate 3",
                "Held-Out Test Accuracy & Macro F1",
                False,
                f"Missing {test_metrics_path}",
            )
        )
    else:
        tm = load_json(test_metrics_path)
        test_acc = float(tm["test_acc"])
        macro_f1 = float(tm["macro_f1"])
        min_class_f1 = min(float(v["f1"]) for v in tm["per_class"].values())
        acc_thresh = 0.70 if smoke else cfg.evaluate.mve_min_test_accuracy
        f1_thresh = 0.70 if smoke else cfg.evaluate.mve_min_macro_f1
        cls_f1_thresh = 0.50 if smoke else 0.9800
        passed_g3 = (
            test_acc >= acc_thresh and macro_f1 >= f1_thresh and min_class_f1 >= cls_f1_thresh
        )
        results.append(
            GateResult(
                "Gate 3",
                "Held-Out Test Accuracy & Macro F1",
                passed_g3,
                f"test_acc={test_acc:.4f} (>={acc_thresh:.4f}), "
                f"macro_f1={macro_f1:.4f} (>={f1_thresh:.4f}), "
                f"min_class_f1={min_class_f1:.4f} (>={cls_f1_thresh:.4f})",
            )
        )

    # Gate 4: Inference Latency & Footprint
    bench_path = root_dir / "artifacts/benchmarks/benchmark_metrics.json"
    if not bench_path.exists():
        results.append(
            GateResult("Gate 4", "Inference Latency & Footprint", False, f"Missing {bench_path}")
        )
    else:
        bm = load_json(bench_path)
        bs1_p95 = float(bm["batch_metrics"]["1"]["p95_ms"])
        trainable_params = int(bm["trainable_params"])
        ckpt_mb = float(bm["checkpoint_size_mb"])
        max_p95 = cfg.evaluate.mve_max_p95_latency_ms
        passed_g4 = bs1_p95 < max_p95 and trainable_params < 1_000_000 and ckpt_mb < 10.0
        results.append(
            GateResult(
                "Gate 4",
                "Inference Latency & Footprint",
                passed_g4,
                f"bs1_p95_ms={bs1_p95:.3f} (<{max_p95:.1f} ms), "
                f"trainable_params={trainable_params:,} (<1,000,000), "
                f"checkpoint_size_mb={ckpt_mb:.2f} (<10.0 MB)",
            )
        )

    # Gate 5: Artifact & Visualization Completeness
    required_files = [
        root_dir / "artifacts/checkpoints/checkpoint_best.pt",
        root_dir / "artifacts/checkpoints/model.safetensors",
        root_dir / "artifacts/reports/plots/loss_curve.png",
        root_dir / "artifacts/reports/plots/accuracy_curve.png",
        root_dir / "artifacts/reports/plots/confusion_matrix.png",
        root_dir / "artifacts/reports/plots/sample_predictions.png",
        root_dir / "artifacts/reports/evaluation_report.md",
        root_dir / "docs/model_card.md",
        root_dir / "docs/dataset_card.md",
    ]
    missing_or_empty = [
        str(p.relative_to(root_dir))
        for p in required_files
        if not p.exists() or p.stat().st_size == 0
    ]
    passed_g5 = len(missing_or_empty) == 0
    details_g5 = (
        f"All {len(required_files)} required artifacts/plots non-empty"
        if passed_g5
        else f"Missing or empty: {missing_or_empty}"
    )
    results.append(
        GateResult("Gate 5", "Artifact & Visualization Completeness", passed_g5, details_g5)
    )

    return results


def run_smoke_mve() -> list[GateResult]:
    """Execute a self-contained 4-epoch MVE pipeline in a temporary directory.

    Returns:
        List of 5 `GateResult` objects from the smoke run.
    """
    repo_root = Path(__file__).resolve().parent.parent
    with tempfile.TemporaryDirectory(prefix="mnist_mve_smoke_") as tmp_str:
        tmp_root = Path(tmp_str)
        processed_dir = tmp_root / "data/processed"

        cfg = load_hydra_config(
            overrides=[
                f"data.raw_dir={tmp_root / 'data/raw'}",
                f"data.processed_dir={processed_dir}",
                "data.download=false",
                "data.allow_synthetic_fallback=true",
                "data.num_synthetic_train=200",
                "data.num_synthetic_test=60",
                "data.batch_size=16",
                "train.epochs=4",
                "train.lr=0.002",
                "train.device=cpu",
                "evaluate.benchmark_warmup_runs=2",
                "evaluate.benchmark_timed_runs=5",
                "wandb.mode=disabled",
                f"paths.artifacts_dir={tmp_root / 'artifacts'}",
                f"paths.checkpoints_dir={tmp_root / 'artifacts/checkpoints'}",
                f"paths.evaluation_dir={tmp_root / 'artifacts/evaluation'}",
                f"paths.benchmarks_dir={tmp_root / 'artifacts/benchmarks'}",
                f"paths.reports_dir={tmp_root / 'artifacts/reports'}",
                f"paths.plots_dir={tmp_root / 'artifacts/reports/plots'}",
                f"paths.templates_dir={repo_root / 'templates'}",
                f"paths.docs_dir={tmp_root / 'docs'}",
            ]
        )

        preprocess_mnist_data(cfg.data)
        train_model(cfg)
        evaluate_checkpoint(cfg)
        benchmark_checkpoint(cfg)
        generate_all_reports(
            cfg,
            template_dir=repo_root / "templates",
            docs_dir=tmp_root / "docs",
        )
        return verify_mve_gates(tmp_root, smoke=True)


def main() -> None:
    """CLI entrypoint for MVE gate verification."""
    parser = argparse.ArgumentParser(
        description="Verify Minimum Viable Experiment (MVE) acceptance criteria gates."
    )
    parser.add_argument(
        "--smoke",
        action="store_true",
        help="Run a fast self-contained 2-epoch synthetic MVE smoke check in a temporary directory.",
    )
    args = parser.parse_args()

    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
    )

    repo_root = Path(__file__).resolve().parent.parent
    gate_results: list[GateResult] = (
        run_smoke_mve() if args.smoke else verify_mve_gates(repo_root, smoke=False)
    )

    mode_label = "SMOKE MVE" if args.smoke else "FULL BASELINE MVE"
    print(f"\n=== {mode_label} ACCEPTANCE GATE ADJUDICATION ===")
    all_passed = True
    for gr in gate_results:
        status = "PASS" if gr.passed else "FAIL"
        print(f"[{status}] {gr.gate_id} ({gr.name}): {gr.details}")
        if not gr.passed:
            all_passed = False

    if not all_passed:
        LOGGER.error("%s verification FAILED one or more gates.", mode_label)
        sys.exit(1)

    LOGGER.info("All 5 %s acceptance gates PASSED!", mode_label)


if __name__ == "__main__":
    main()
